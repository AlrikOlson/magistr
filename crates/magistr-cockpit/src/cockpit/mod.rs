//! The Elm-style core: a [`Model`] of the cockpit, the [`Msg`]s that
//! change it, [`update`] folding a message into the model and answering
//! with [`Cmd`]s for the runtime, and [`view`] turning the model into a
//! layout tree for the renderer.
//!
//! `update` and `view` are pure: no clock, no file, no process, no
//! terminal — `tests/purity.rs` fails the build of this module if one
//! sneaks in. Time reaches `view` only through the [`FrameClock`] the
//! runtime hands it.

