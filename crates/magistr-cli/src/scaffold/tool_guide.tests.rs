use super::*;

#[test]
fn tool_guide_contains_auto_generated_header() {
    let guide = build_tool_guide();
    assert!(guide.contains("Auto-generated by magistr"));
    assert!(guide.contains("DO NOT EDIT"));
}

#[test]
fn tool_guide_contains_all_workbench_tools() {
    let guide = build_tool_guide();
    for (tool, replaces, _) in WORKBENCH_TOOLS {
        assert!(
            guide.contains(&format!("| `{tool}` | {replaces} |")),
            "tool guide should contain workbench tool row: {tool}"
        );
    }
    assert_eq!(
        WORKBENCH_TOOLS.len(),
        9,
        "the eight reference tools and the native write"
    );
}

#[test]
fn tool_guide_contains_all_magistr_tools() {
    let guide = build_tool_guide();
    for (tool, _) in MAGISTR_TOOLS {
        assert!(
            guide.contains(tool),
            "tool guide should contain magistr tool: {tool}"
        );
    }
    assert_eq!(
        MAGISTR_TOOLS.iter().map(|(t, _)| *t).collect::<Vec<_>>(),
        [
            "magistr_gate",
            "magistr_format",
            "magistr_set_phase",
            "magistr_delete",
            "magistr_list"
        ],
        "the roadmap lives in think-and-ship; magistr keeps gate/format/set_phase/delete/list"
    );
}

#[test]
fn tool_guide_contains_the_think_and_ship_families() {
    let guide = build_tool_guide();
    assert!(guide.contains("## Roadmap, Reasoning & Execution (think-and-ship)"));
    for (family, purpose, _) in THINK_AND_SHIP_FAMILIES {
        assert!(
            guide.contains(&format!("| `{family}` | {purpose} |")),
            "tool guide should contain family row: {family}"
        );
    }
    assert_eq!(THINK_AND_SHIP_FAMILIES.len(), 4, "the four families");
    assert!(guide.contains("`ROADMAP.md` is a generated view"));
}

#[test]
fn tool_guide_points_at_the_routing_skill() {
    let guide = build_tool_guide();
    assert!(guide.contains(".claude/skills/workbench-routing/SKILL.md"));
    assert!(guide.contains("Git stays in the shell"));
    assert!(guide.contains("Recommended workflow"));
}

#[test]
fn tool_guide_contains_preferences() {
    let guide = build_tool_guide();
    assert!(guide.contains("## Tool Preferences"));
    assert!(guide.contains("instead of Grep/grep"));
    assert!(guide.contains("magistr_gate"));
    assert!(guide.contains("sub-agents"));
}

#[test]
fn tool_guide_does_not_contain_stale_references() {
    let guide = build_tool_guide();
    for stale in [
        "firecrawl",
        "web_search",
        "subagent_type",
        "scope_",
        "magistr-scope",
        "iris",
        "ministr",
        "magistr_roadmap",
    ] {
        assert!(
            !guide.contains(stale),
            "tool guide should not reference {stale}"
        );
    }
}

