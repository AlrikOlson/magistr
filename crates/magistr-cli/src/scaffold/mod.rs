/// MCP server keys magistr used to manage — or never should have been
/// configured beside it — stripped whenever `.mcp.json` is merged or the
/// scaffold is removed, so a re-init retires them. `think-and-ship` is here
/// because `magistr mcp-serve` serves the same four families in-process over
/// the same store: a standalone `think-and-ship serve` on the same project
/// is a second process holding its own copy of the execution and roadmap
/// state (tas-ship-state-two-servers).
pub(super) const LEGACY_MCP_SERVERS: &[&str] =
    &["magistr-scope", "iris", "ministr", "think-and-ship"];

/// Whether an MCP server entry launches something from inside the working
/// tree: its command or one of its arguments names an existing *file* in the
/// project (relative, or absolute-but-inside). Such an entry is a deliberate
/// dogfooding choice — `bun run src/main.ts .` in the workbench-mcp repo —
/// and a re-init must not replace it with the installed binary. A stale
/// generated entry's path arguments are directories (the project root
/// itself), so it is still rewritten to the portable form.
pub(super) fn is_working_tree_entry(dir: &Path, entry: &serde_json::Value) -> bool {
    let mut candidates: Vec<&str> = Vec::new();
    if let Some(cmd) = entry.get("command").and_then(|v| v.as_str()) {
        candidates.push(cmd);
    }
    if let Some(args) = entry.get("args").and_then(|v| v.as_array()) {
        candidates.extend(args.iter().filter_map(|a| a.as_str()));
    }
    candidates.iter().any(|c| {
        let path = Path::new(c);
        if path.is_absolute() {
            path.starts_with(dir) && path.is_file()
        } else {
            // A bare word ("bun", "run") joins to a path that is not a file.
            dir.join(path).is_file()
        }
    })
}

/// Recognize only the plain launch lines this scaffold emitted. Everything else
/// is an explicit override, including a launcher that is not installed yet.
fn is_generated_mcp_entry(dir: &Path, key: &str, entry: &serde_json::Value) -> bool {
    let Some(object) = entry.as_object() else {
        return false;
    };
    if object.len() != 3 || entry.get("type").and_then(|v| v.as_str()) != Some("stdio") {
        return false;
    }
    let Some(command) = entry.get("command").and_then(|v| v.as_str()) else {
        return false;
    };
    let Some(args) = entry.get("args").and_then(|v| v.as_array()) else {
        return false;
    };
    let root = match (key, command, args.as_slice()) {
        ("magistr", "magistr", [verb, root]) if verb.as_str() == Some("mcp-serve") => root,
        ("workbench-mcp", "workbench-mcp", [root]) => root,
        ("magistr" | "workbench-mcp", "magistr", [verb, target, root])
            if verb.as_str() == Some("mcp-launch") && target.as_str() == Some(key) =>
        {
            root
        }
        _ => return false,
    };
    root.as_str()
        .is_some_and(|root| root == "." || Path::new(root) == dir)
}

/// The extra MCP entries the interview selected, keyed by server name.
fn selected_mcp_entries(vars: &HashMap<String, String>) -> HashMap<String, serde_json::Value> {
    vars.get("selected_mcp_servers")
        .map(|selected| {
            interview::build_extra_mcp_entries(
                &selected
                    .split(',')
                    .filter(|s| !s.is_empty())
                    .map(String::from)
                    .collect::<Vec<_>>(),
            )
        })
        .unwrap_or_default()
}

/// The planned `.mcp.json`: magistr's server entries merged into the
/// existing document (user entries and working-tree launches kept, stale
/// generated entries rewritten, retired servers removed), or a fresh
/// document when there is none. One computation serves preview and
/// generation, so the two cannot disagree.
pub(crate) fn mcp_json_change(dir: &Path, vars: &HashMap<String, String>) -> Result<PlannedChange> {
    let magistr_value = mcp_config::build(vars)?;
    let magistr_servers = magistr_value
        .get("mcpServers")
        .and_then(|v| v.as_object())
        .cloned()
        .unwrap_or_default();

    let existing = read_target(dir, ".mcp.json");
    let existing_str = match existing {
        Ok(existing) => existing,
        Err(refusal) => {
            return Ok(PlannedChange::refused(
                ".mcp.json",
                refusal,
                None,
                Ownership::Shared,
            ));
        }
    };

    let mut doc = match &existing_str {
        None => serde_json::json!({ "mcpServers": {} }),
        Some(text) => {
            serde_json::from_str(text).unwrap_or_else(|_| serde_json::json!({ "mcpServers": {} }))
        }
    };
    let obj = doc
        .as_object_mut()
        .unwrap_or_else(|| unreachable!("parsed JSON is always an object due to fallback above"));
    let servers = obj
        .entry("mcpServers")
        .or_insert_with(|| serde_json::json!({}));
    let servers_map = match servers.as_object_mut() {
        Some(m) => m,
        None => {
            *servers = serde_json::json!({});
            servers.as_object_mut().expect("just created")
        }
    };

    for (key, value) in &magistr_servers {
        if let Some(current) = servers_map.get(key)
            && (is_working_tree_entry(dir, current) || !is_generated_mcp_entry(dir, key, current))
        {
            continue;
        }
        servers_map.insert(key.clone(), value.clone());
    }
    for (key, value) in selected_mcp_entries(vars) {
        servers_map.entry(key).or_insert(value);
    }
    for key in LEGACY_MCP_SERVERS {
        servers_map.remove(*key);
    }

    let merged = format!(
        "{}\n",
        serde_json::to_string_pretty(&doc).with_context(MagistrError::Config)?
    );
    Ok(PlannedChange::merged(".mcp.json", existing_str, merged))
}

// ── Gitignore merge ────────────────────────────────────────────────

pub(super) const GITIGNORE_SECTION_START: &str =
    "# ── magistr managed ── DO NOT EDIT between markers ──";
pub(super) const GITIGNORE_SECTION_END: &str = "# ── end magistr ──";

fn gitignore_content(language: &str) -> &'static str {
    match language {
        "rust" => include_str!("../../templates/gitignore/rust.gitignore"),
        "typescript" | "javascript" => {
            include_str!("../../templates/gitignore/typescript.gitignore")
        }
        "python" => include_str!("../../templates/gitignore/python.gitignore"),
        "go" => include_str!("../../templates/gitignore/go.gitignore"),
        "java" => include_str!("../../templates/gitignore/java.gitignore"),
        "ruby" => include_str!("../../templates/gitignore/ruby.gitignore"),
        "elixir" => include_str!("../../templates/gitignore/elixir.gitignore"),
        "kotlin" => include_str!("../../templates/gitignore/kotlin.gitignore"),
        "swift" => include_str!("../../templates/gitignore/swift.gitignore"),
        "cpp" | "c++" => include_str!("../../templates/gitignore/cpp.gitignore"),
        "csharp" | "c#" => include_str!("../../templates/gitignore/csharp.gitignore"),
        _ => "",
    }
}

fn build_gitignore_section(language: &str) -> String {
    let mut patterns = Vec::new();
    for source in [
        STATIC_GITIGNORE_MAGISTR,
        STATIC_GITIGNORE_DEFAULT,
        gitignore_content(language),
    ] {
        for line in source.lines() {
            let trimmed = line.trim();
            if !trimmed.is_empty() && !trimmed.starts_with('#') && !patterns.contains(&trimmed) {
                patterns.push(trimmed);
            }
        }
    }
    patterns.join("\n")
}

/// The planned `.gitignore`: magistr's managed section merged into the
/// existing file, or a fresh file when there is none.
pub(crate) fn gitignore_change(dir: &Path, vars: &HashMap<String, String>) -> PlannedChange {
    let language = vars
        .get("language")
        .map(|s| s.as_str())
        .unwrap_or("unknown");
    let section_body = build_gitignore_section(language);
    match read_target(dir, ".gitignore") {
        Ok(existing) => {
            let merged = merge_gitignore_content(existing.as_deref().unwrap_or(""), &section_body);
            PlannedChange::merged(".gitignore", existing, merged)
        }
        Err(refusal) => PlannedChange::refused(".gitignore", refusal, None, Ownership::Shared),
    }
}

pub(crate) fn merge_gitignore_content(existing: &str, section_body: &str) -> String {
    let has_start = existing.contains(GITIGNORE_SECTION_START);
    let has_end = existing.contains(GITIGNORE_SECTION_END);

    if has_start && has_end {
        let start_pos = existing.find(GITIGNORE_SECTION_START).unwrap();
        let end_pos = existing.find(GITIGNORE_SECTION_END).unwrap();
        let end_line_end = existing[end_pos..]
            .find('\n')
            .map(|i| end_pos + i + 1)
            .unwrap_or(existing.len());

        let before = &existing[..start_pos];
        let after = &existing[end_line_end..];

        let new_section = format_gitignore_section(section_body);
        format!("{before}{new_section}{after}")
    } else {
        let existing_patterns: std::collections::HashSet<&str> = existing
            .lines()
            .map(|l| l.trim())
            .filter(|l| !l.is_empty() && !l.starts_with('#'))
            .collect();

        let filtered: Vec<&str> = section_body
            .lines()
            .filter(|l| !existing_patterns.contains(l.trim()))
            .collect();

        if filtered.is_empty() {
            return existing.to_string();
        }

        let new_section = format_gitignore_section(&filtered.join("\n"));

        // Exactly one blank line separates the user's patterns from the
        // managed block — asked of the *result* rather than pushed
        // unconditionally, because the merge is handed a file that
        // already ends in a blank line more often than not: an explicit
        // reset cuts the managed block out and leaves the separator
        // behind, so a push per run grew a project's `.gitignore` by a
        // blank line for ever.
        let mut result = existing.trim_end().to_string();
        if !result.is_empty() {
            result.push_str("\n\n");
        }
        result.push_str(&new_section);
        result
    }
}

fn format_gitignore_section(body: &str) -> String {
    format!("{GITIGNORE_SECTION_START}\n{body}\n{GITIGNORE_SECTION_END}\n")
}

/// Generate a unified diff between old and new content for a given file path.
pub(crate) fn unified_diff(path: &str, old: &str, new: &str) -> String {
    use similar::TextDiff;

    let diff = TextDiff::from_lines(old, new);
    let mut output = String::new();

    output.push_str(&format!("--- a/{path}\n"));
    output.push_str(&format!("+++ b/{path}\n"));

    for hunk in diff.unified_diff().context_radius(3).iter_hunks() {
        output.push_str(&format!("{hunk}"));
    }

    output
}

/// The changes the template plugins installed in the registry the captured
/// inputs name would make under `.claude/`. A missing or unreadable
/// registry, or a plugin whose template configuration cannot be loaded,
/// plans nothing; an unreadable template source is a refusal for its
/// destination rather than a silent skip.
pub(crate) fn plan_template_plugins(
    dir: &Path,
    vars: &HashMap<String, String>,
    inputs: &crate::config::inputs::ProjectInputs,
) -> Vec<PlannedChange> {
    let registry = match crate::plugin::PluginRegistry::open(inputs) {
        Some(Ok(r)) => r,
        _ => return Vec::new(),
    };

    let mut changes = Vec::new();
    for installed in registry.list() {
        if installed.manifest.kind != crate::plugin::PluginKind::Template {
            continue;
        }
        let plugin_dir = registry.plugin_dir(&installed.manifest.name);
        let Ok(config) = crate::plugin::load_template_config(&plugin_dir) else {
            continue;
        };
        for tmpl_file in &config.files {
            let src_path = plugin_dir.join(&tmpl_file.src);
            let dest = format!(".claude/{}", tmpl_file.dest);
            let existing = match read_target(dir, &dest) {
                Ok(existing) => existing,
                Err(refusal) => {
                    changes.push(PlannedChange::refused(
                        &dest,
                        refusal,
                        None,
                        Ownership::Internal,
                    ));
                    continue;
                }
            };
            let ownership = if existing.is_some() {
                Ownership::Internal
            } else {
                Ownership::Unclaimed
            };
            changes.push(match std::fs::read_to_string(&src_path) {
                Ok(template) => {
                    let mut change =
                        PlannedChange::merged(&dest, existing, substitute(&template, vars));
                    change.ownership = ownership;
                    change
                }
                Err(error) => PlannedChange::refused(
                    &dest,
                    Refusal::UnreadableSource {
                        source: src_path.display().to_string(),
                        cause: error.to_string(),
                    },
                    existing,
                    ownership,
                ),
            });
        }
    }
    changes
}

