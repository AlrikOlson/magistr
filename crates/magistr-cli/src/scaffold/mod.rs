const GITIGNORE_SECTION_START: &str = "# ── magistr managed ── DO NOT EDIT between markers ──";
const GITIGNORE_SECTION_END: &str = "# ── end magistr ──";

fn gitignore_content(language: &str) -> &'static str {
    match language {
        "rust" => include_str!("../../templates/gitignore/rust.gitignore"),
        "typescript" | "javascript" => {
            include_str!("../../templates/gitignore/typescript.gitignore")
        }
        "python" => include_str!("../../templates/gitignore/python.gitignore"),
        "go" => include_str!("../../templates/gitignore/go.gitignore"),
        "java" => include_str!("../../templates/gitignore/java.gitignore"),
        "ruby" => include_str!("../../templates/gitignore/ruby.gitignore"),
        "elixir" => include_str!("../../templates/gitignore/elixir.gitignore"),
        "kotlin" => include_str!("../../templates/gitignore/kotlin.gitignore"),
        "swift" => include_str!("../../templates/gitignore/swift.gitignore"),
        "cpp" | "c++" => include_str!("../../templates/gitignore/cpp.gitignore"),
        "csharp" | "c#" => include_str!("../../templates/gitignore/csharp.gitignore"),
        _ => "",
    }
}

fn build_gitignore_section(language: &str) -> String {
    let mut patterns = Vec::new();
    for source in [
        STATIC_GITIGNORE_MAGISTR,
        STATIC_GITIGNORE_DEFAULT,
        gitignore_content(language),
    ] {
        for line in source.lines() {
            let trimmed = line.trim();
            if !trimmed.is_empty() && !trimmed.starts_with('#') && !patterns.contains(&trimmed) {
                patterns.push(trimmed);
            }
        }
    }
    patterns.join("\n")
}

pub(crate) fn merge_gitignore(dir: &Path, vars: &HashMap<String, String>) -> Result<()> {
    let gi_path = dir.join(".gitignore");
    let language = vars
        .get("language")
        .map(|s| s.as_str())
        .unwrap_or("unknown");
    let section_body = build_gitignore_section(language);

    let existing = std::fs::read_to_string(&gi_path).unwrap_or_default();

    let result = merge_gitignore_content(&existing, &section_body);

    std::fs::write(&gi_path, result.as_bytes()).map_err(|e| MagistrError::io(&gi_path, e))
}

pub(crate) fn merge_gitignore_content(existing: &str, section_body: &str) -> String {
    let has_start = existing.contains(GITIGNORE_SECTION_START);
    let has_end = existing.contains(GITIGNORE_SECTION_END);

    if has_start && has_end {
        let start_pos = existing.find(GITIGNORE_SECTION_START).unwrap();
        let end_pos = existing.find(GITIGNORE_SECTION_END).unwrap();
        let end_line_end = existing[end_pos..]
            .find('\n')
            .map(|i| end_pos + i + 1)
            .unwrap_or(existing.len());

        let before = &existing[..start_pos];
        let after = &existing[end_line_end..];

        let new_section = format_gitignore_section(section_body);
        format!("{before}{new_section}{after}")
    } else {
        let existing_patterns: std::collections::HashSet<&str> = existing
            .lines()
            .map(|l| l.trim())
            .filter(|l| !l.is_empty() && !l.starts_with('#'))
            .collect();

        let filtered: Vec<&str> = section_body
            .lines()
            .filter(|l| !existing_patterns.contains(l.trim()))
            .collect();

        if filtered.is_empty() {
            return existing.to_string();
        }

        let new_section = format_gitignore_section(&filtered.join("\n"));

        // Exactly one blank line separates the user's patterns from the
        // managed block — asked of the *result* rather than pushed
        // unconditionally, because the merge is handed a file that
        // already ends in a blank line more often than not: an explicit
        // reset cuts the managed block out and leaves the separator
        // behind, so a push per run grew a project's `.gitignore` by a
        // blank line for ever.
        let mut result = existing.trim_end().to_string();
        if !result.is_empty() {
            result.push_str("\n\n");
        }
        result.push_str(&new_section);
        result
    }
}

fn format_gitignore_section(body: &str) -> String {
    format!("{GITIGNORE_SECTION_START}\n{body}\n{GITIGNORE_SECTION_END}\n")
}

pub(crate) fn preview_gitignore(
    dir: &Path,
    vars: &HashMap<String, String>,
) -> Result<(String, FileAction)> {
    let gi_path = dir.join(".gitignore");
    let language = vars
        .get("language")
        .map(|s| s.as_str())
        .unwrap_or("unknown");
    let section_body = build_gitignore_section(language);

    let existing = std::fs::read_to_string(&gi_path).ok();
    let merged = merge_gitignore_content(existing.as_deref().unwrap_or(""), &section_body);

    let action = match existing {
        None => FileAction::Create,
        Some(ref old) if *old == merged => FileAction::Unchanged,
        Some(_) => FileAction::Overwrite,
    };

    Ok((merged, action))
}

pub(crate) fn remove_magistr_gitignore_entries(dir: &Path) -> Result<()> {
    let gi_path = dir.join(".gitignore");
    if !gi_path.exists() {
        return Ok(());
    }

    let content = match std::fs::read_to_string(&gi_path) {
        Ok(c) => c,
        Err(_) => return Ok(()),
    };

    let has_start = content.contains(GITIGNORE_SECTION_START);
    let has_end = content.contains(GITIGNORE_SECTION_END);

    if !has_start || !has_end {
        return Ok(());
    }

    let start_pos = content.find(GITIGNORE_SECTION_START).unwrap();
    let end_pos = content.find(GITIGNORE_SECTION_END).unwrap();
    let end_line_end = content[end_pos..]
        .find('\n')
        .map(|i| end_pos + i + 1)
        .unwrap_or(content.len());

    let before = &content[..start_pos];
    let after = &content[end_line_end..];
    let result = format!("{before}{after}");
    let trimmed = result.trim();

    if trimmed.is_empty() {
        let _ = std::fs::remove_file(&gi_path);
    } else {
        std::fs::write(&gi_path, result.as_bytes()).map_err(|e| MagistrError::io(&gi_path, e))?;
    }

    Ok(())
}

/// Generate a unified diff between old and new content for a given file path.
pub(crate) fn unified_diff(path: &str, old: &str, new: &str) -> String {
    use similar::TextDiff;

    let diff = TextDiff::from_lines(old, new);
    let mut output = String::new();

    output.push_str(&format!("--- a/{path}\n"));
    output.push_str(&format!("+++ b/{path}\n"));

    for hunk in diff.unified_diff().context_radius(3).iter_hunks() {
        output.push_str(&format!("{hunk}"));
    }

    output
}

/// Apply template files from installed template plugins.
pub(crate) fn apply_template_plugins(dir: &Path, vars: &HashMap<String, String>) -> Vec<String> {
    let base_dir = match crate::plugin::plugins_dir() {
        Some(d) => d,
        None => return Vec::new(),
    };

    let registry = match crate::plugin::PluginRegistry::load(&base_dir) {
        Ok(r) => r,
        Err(_) => return Vec::new(),
    };

    let mut written = Vec::new();

    for installed in registry.list() {
        if installed.manifest.kind != crate::plugin::PluginKind::Template {
            continue;
        }

        let plugin_dir = registry.plugin_dir(&installed.manifest.name);
        let config = match crate::plugin::load_template_config(&plugin_dir) {
            Ok(c) => c,
            Err(_) => continue,
        };

        for tmpl_file in &config.files {
            let src_path = plugin_dir.join(&tmpl_file.src);
            let dest_path = dir.join(".claude").join(&tmpl_file.dest);

            let content = match std::fs::read_to_string(&src_path) {
                Ok(c) => substitute(&c, vars),
                Err(_) => continue,
            };

            if let Some(parent) = dest_path.parent()
                && std::fs::create_dir_all(parent).is_err()
            {
                continue;
            }

            if std::fs::write(&dest_path, &content).is_ok() {
                let rel_path = format!(".claude/{}", tmpl_file.dest);
                written.push(rel_path);
            }
        }
    }

    written
}

