//! CI workflow generation — produce GitHub Actions YAML from detected stack.
//!
//! Generates `.github/workflows/quality-gates.yml` based on detected language,
//! package manager, and quality gate commands. Supports Rust, TypeScript/JavaScript,
//! Python, Go, Ruby, Java, Kotlin, and generic stacks.

use std::path::{Path, PathBuf};

use crate::error::{MagistrError, Result};
use crate::types::{Language, PackageManager, QualityGate};

/// Output path for the generated CI workflow file.
pub(crate) const WORKFLOW_PATH: &str = ".github/workflows/quality-gates.yml";

/// Result of writing a CI workflow file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum CiWriteResult {
    /// File was created successfully.
    Created(PathBuf),
    /// File already exists — use `--force` to overwrite.
    AlreadyExists(PathBuf),
    /// File was overwritten (force mode).
    Overwritten(PathBuf),
}

/// Generate GitHub Actions workflow YAML from stack metadata.
///
/// Produces a complete workflow file that:
/// - Triggers on push to main and pull requests
/// - Sets up the correct language toolchain
/// - Installs dependencies
/// - Runs all quality gate commands (check, test, lint)
#[must_use]
pub(crate) fn generate_workflow(
    language: Language,
    package_manager: PackageManager,
    quality_gate: &QualityGate,
) -> String {
    let mut yaml = String::new();

    // Header
    yaml.push_str("# Quality gate CI — generated by magistr\n");
    yaml.push_str("# https://github.com/AlrikOlson/magistr\n");
    yaml.push('\n');
    yaml.push_str("name: Quality Gates\n");
    yaml.push('\n');
    yaml.push_str("on:\n");
    yaml.push_str("  push:\n");
    yaml.push_str("    branches: [main, master]\n");
    yaml.push_str("  pull_request:\n");
    yaml.push_str("    branches: [main, master]\n");
    yaml.push('\n');
    yaml.push_str("jobs:\n");
    yaml.push_str("  quality-gates:\n");
    yaml.push_str("    runs-on: ubuntu-latest\n");
    yaml.push_str("    steps:\n");
    yaml.push_str("      - uses: actions/checkout@v4\n");

    // Language-specific setup
    append_setup_steps(&mut yaml, language, package_manager);

    if [&quality_gate.check, &quality_gate.test, &quality_gate.lint]
        .iter()
        .any(|command| command.contains("cargo nextest"))
    {
        yaml.push_str("\n      - name: Install nextest\n");
        yaml.push_str("        run: cargo install cargo-nextest --locked\n");
    }

    // Quality gate steps
    yaml.push('\n');
    yaml.push_str("      - name: Check\n");
    yaml.push_str(&format!("        run: {}\n", &quality_gate.check));
    yaml.push('\n');
    yaml.push_str("      - name: Test\n");
    yaml.push_str(&format!("        run: {}\n", &quality_gate.test));
    yaml.push('\n');
    yaml.push_str("      - name: Lint\n");
    yaml.push_str(&format!("        run: {}\n", &quality_gate.lint));

    yaml
}

/// Append language-specific setup steps (toolchain install, dependency install).
fn append_setup_steps(yaml: &mut String, language: Language, package_manager: PackageManager) {
    match language {
        Language::Rust => {
            yaml.push('\n');
            yaml.push_str("      - name: Install Rust toolchain\n");
            yaml.push_str("        uses: dtolnay/rust-toolchain@stable\n");
            yaml.push_str("        with:\n");
            yaml.push_str("          components: clippy, rustfmt\n");
            yaml.push('\n');
            yaml.push_str("      - name: Cache cargo\n");
            yaml.push_str("        uses: actions/cache@v4\n");
            yaml.push_str("        with:\n");
            yaml.push_str("          path: |\n");
            yaml.push_str("            ~/.cargo/bin/\n");
            yaml.push_str("            ~/.cargo/registry/index/\n");
            yaml.push_str("            ~/.cargo/registry/cache/\n");
            yaml.push_str("            ~/.cargo/git/db/\n");
            yaml.push_str("            target/\n");
            yaml.push_str(
                "          key: ${{ runner.os }}-cargo-${{ hashFiles('**/Cargo.lock') }}\n",
            );
        }
        Language::TypeScript | Language::JavaScript => {
            append_node_setup(yaml, package_manager);
        }
        Language::Python => {
            yaml.push('\n');
            yaml.push_str("      - name: Set up Python\n");
            yaml.push_str("        uses: actions/setup-python@v5\n");
            yaml.push_str("        with:\n");
            yaml.push_str("          python-version: '3.12'\n");
            append_python_install(yaml, package_manager);
        }
        Language::Go => {
            yaml.push('\n');
            yaml.push_str("      - name: Set up Go\n");
            yaml.push_str("        uses: actions/setup-go@v5\n");
            yaml.push_str("        with:\n");
            yaml.push_str("          go-version: 'stable'\n");
        }
        Language::Ruby => {
            yaml.push('\n');
            yaml.push_str("      - name: Set up Ruby\n");
            yaml.push_str("        uses: ruby/setup-ruby@v1\n");
            yaml.push_str("        with:\n");
            yaml.push_str("          ruby-version: '3.3'\n");
            yaml.push_str("          bundler-cache: true\n");
        }
        Language::Java | Language::Kotlin => {
            yaml.push('\n');
            yaml.push_str("      - name: Set up JDK\n");
            yaml.push_str("        uses: actions/setup-java@v4\n");
            yaml.push_str("        with:\n");
            yaml.push_str("          distribution: 'temurin'\n");
            yaml.push_str("          java-version: '21'\n");
            append_java_cache(yaml, package_manager);
        }
        Language::Elixir => {
            yaml.push('\n');
            yaml.push_str("      - name: Set up Elixir\n");
            yaml.push_str("        uses: erlef/setup-beam@v1\n");
            yaml.push_str("        with:\n");
            yaml.push_str("          elixir-version: '1.16'\n");
            yaml.push_str("          otp-version: '26'\n");
            yaml.push('\n');
            yaml.push_str("      - name: Install dependencies\n");
            yaml.push_str("        run: mix deps.get\n");
        }
        Language::Swift => {
            yaml.push('\n');
            yaml.push_str("      - name: Set up Swift\n");
            yaml.push_str("        uses: swift-actions/setup-swift@v2\n");
        }
        _ => {
            // Generic — no special setup, just run the gate commands
        }
    }
}

/// Append Node.js setup and dependency install steps.
fn append_node_setup(yaml: &mut String, package_manager: PackageManager) {
    yaml.push('\n');
    yaml.push_str("      - name: Set up Node.js\n");
    yaml.push_str("        uses: actions/setup-node@v4\n");
    yaml.push_str("        with:\n");
    yaml.push_str("          node-version: '22'\n");

    match package_manager {
        PackageManager::Pnpm => {
            yaml.push('\n');
            yaml.push_str("      - name: Install pnpm\n");
            yaml.push_str("        uses: pnpm/action-setup@v4\n");
            yaml.push('\n');
            yaml.push_str("      - name: Install dependencies\n");
            yaml.push_str("        run: pnpm install --frozen-lockfile\n");
        }
        PackageManager::Yarn => {
            yaml.push('\n');
            yaml.push_str("      - name: Install dependencies\n");
            yaml.push_str("        run: yarn install --frozen-lockfile\n");
        }
        PackageManager::Bun => {
            yaml.push('\n');
            yaml.push_str("      - name: Install Bun\n");
            yaml.push_str("        uses: oven-sh/setup-bun@v2\n");
            yaml.push('\n');
            yaml.push_str("      - name: Install dependencies\n");
            yaml.push_str("        run: bun install --frozen-lockfile\n");
        }
        _ => {
            // npm is the default for Node.js projects
            yaml.push('\n');
            yaml.push_str("      - name: Install dependencies\n");
            yaml.push_str("        run: npm ci\n");
        }
    }
}

/// Append Python dependency install step.
fn append_python_install(yaml: &mut String, package_manager: PackageManager) {
    yaml.push('\n');
    yaml.push_str("      - name: Install dependencies\n");
    match package_manager {
        PackageManager::Poetry => {
            yaml.push_str("        run: |\n");
            yaml.push_str("          pip install poetry\n");
            yaml.push_str("          poetry install\n");
        }
        PackageManager::Uv => {
            yaml.push_str("        run: |\n");
            yaml.push_str("          pip install uv\n");
            yaml.push_str("          uv sync\n");
        }
        _ => {
            yaml.push_str("        run: pip install -r requirements.txt\n");
        }
    }
}

/// Append Java/Kotlin build tool cache step.
fn append_java_cache(yaml: &mut String, package_manager: PackageManager) {
    match package_manager {
        PackageManager::Gradle => {
            yaml.push('\n');
            yaml.push_str("      - name: Cache Gradle\n");
            yaml.push_str("        uses: actions/cache@v4\n");
            yaml.push_str("        with:\n");
            yaml.push_str("          path: |\n");
            yaml.push_str("            ~/.gradle/caches\n");
            yaml.push_str("            ~/.gradle/wrapper\n");
            yaml.push_str(
                "          key: ${{ runner.os }}-gradle-${{ hashFiles('**/*.gradle*', '**/gradle-wrapper.properties') }}\n",
            );
        }
        PackageManager::Maven => {
            yaml.push('\n');
            yaml.push_str("      - name: Cache Maven\n");
            yaml.push_str("        uses: actions/cache@v4\n");
            yaml.push_str("        with:\n");
            yaml.push_str("          path: ~/.m2/repository\n");
            yaml.push_str("          key: ${{ runner.os }}-maven-${{ hashFiles('**/pom.xml') }}\n");
        }
        _ => {}
    }
}

/// Write the CI workflow file to the project directory.
///
/// Creates `.github/workflows/` directory if needed.
/// Returns `AlreadyExists` if the file already exists and `force` is false.
pub(crate) fn write_workflow(dir: &Path, content: &str, force: bool) -> Result<CiWriteResult> {
    let full_path = dir.join(WORKFLOW_PATH);

    if full_path.exists() && !force {
        return Ok(CiWriteResult::AlreadyExists(full_path));
    }

    let is_overwrite = full_path.exists();

    // Create parent directories
    if let Some(parent) = full_path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| MagistrError::io(parent, e))?;
    }

    std::fs::write(&full_path, content).map_err(|e| MagistrError::io(&full_path, e))?;

    if is_overwrite {
        Ok(CiWriteResult::Overwritten(full_path))
    } else {
        Ok(CiWriteResult::Created(full_path))
    }
}

