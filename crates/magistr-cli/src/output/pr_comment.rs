//! PR comment markdown generator.
//!
//! Produces a Markdown summary of an iteration or validation run, suitable
//! for posting as a GitHub PR comment via `gh pr comment`.
//!
//! The summary includes:
//! - Quality gate results table (gate, status, duration)
//! - Spec progress bar (if iteration context is available)
//! - Total duration and cost (if available)

use std::fmt::Write;

use crate::validate::ValidationResult;

/// Optional iteration context for richer PR comments.
#[allow(dead_code)] // Public API — consumed by headless iteration output (E3.6.1)
#[derive(Debug, Clone)]
pub(crate) struct IterationContext {
    /// Current iteration number (1-based).
    pub iteration: u32,
    /// Total iterations configured.
    pub max_iterations: u32,
    /// Spec items checked after this iteration.
    pub spec_checked: usize,
    /// Total spec items.
    pub spec_total: usize,
    /// Cost in USD (if available).
    pub cost_usd: Option<f64>,
}

/// Generate a Markdown PR comment from validation results.
///
/// If `iteration` is provided, includes spec progress and iteration info.
#[allow(dead_code)] // Public API — consumed by headless iteration output (E3.6.1)
#[must_use]
pub(crate) fn generate_pr_comment(
    result: &ValidationResult,
    iteration: Option<&IterationContext>,
) -> String {
    let mut md = String::new();

    // Header
    writeln!(md, "## magistr iteration summary").expect("write to String");
    writeln!(md).expect("write to String");

    // Iteration info
    if let Some(ctx) = iteration {
        let pct = if ctx.spec_total > 0 {
            (ctx.spec_checked as f64 / ctx.spec_total as f64 * 100.0) as u32
        } else {
            0
        };
        let bar = progress_bar(pct, 20);
        writeln!(
            md,
            "**Iteration** {}/{} | **Spec progress** {bar} {}/{} ({pct}%)",
            ctx.iteration, ctx.max_iterations, ctx.spec_checked, ctx.spec_total,
        )
        .expect("write to String");
        writeln!(md).expect("write to String");
    }

    // Gate results table
    writeln!(md, "| Gate | Status | Duration |").expect("write to String");
    writeln!(md, "|------|--------|----------|").expect("write to String");

    for gate_result in &result.results {
        let status = if gate_result.passed { "PASS" } else { "FAIL" };
        let icon = if gate_result.passed { "✅" } else { "❌" };
        let duration = format!("{:.1}s", gate_result.duration.as_secs_f64());
        writeln!(
            md,
            "| {} | {icon} {status} | {duration} |",
            gate_result.gate.label(),
        )
        .expect("write to String");
    }

    writeln!(md).expect("write to String");

    // Overall status
    let total_duration = result.total_duration();
    if result.all_passed() {
        writeln!(
            md,
            "**All gates passed** in {:.1}s",
            total_duration.as_secs_f64()
        )
        .expect("write to String");
    } else {
        writeln!(
            md,
            "**{} gate(s) failed** ({} passed) in {:.1}s",
            result.failed_count(),
            result.passed_count(),
            total_duration.as_secs_f64(),
        )
        .expect("write to String");
    }

    // Cost
    if let Some(ctx) = iteration
        && let Some(cost) = ctx.cost_usd
    {
        writeln!(md, " | **Cost** ${cost:.2}").expect("write to String");
    }

    writeln!(md).expect("write to String");
    writeln!(md, "---").expect("write to String");
    write!(
        md,
        "*Generated by [magistr](https://github.com/AlrikOlson/magistr)*"
    )
    .expect("write to String");

    md
}

/// Render a text progress bar: `[████████░░░░░░░░░░░░]`
fn progress_bar(pct: u32, width: usize) -> String {
    let filled = (pct as usize * width) / 100;
    let empty = width.saturating_sub(filled);
    format!("`[{}{}]`", "█".repeat(filled), "░".repeat(empty))
}

