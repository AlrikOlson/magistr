use std::time::Duration;

use super::*;
use crate::validate::{Gate, GateResult, ValidationResult};

fn make_gate_result(gate: Gate, passed: bool, secs: f64) -> GateResult {
    GateResult {
        gate,
        passed,
        duration: Duration::from_secs_f64(secs),
        output: String::new(),
        command: format!("cmd-{}", gate.label()),
    }
}

fn all_pass_result() -> ValidationResult {
    ValidationResult {
        results: vec![
            make_gate_result(Gate::Check, true, 1.2),
            make_gate_result(Gate::Test, true, 5.3),
            make_gate_result(Gate::Lint, true, 0.8),
        ],
    }
}

fn mixed_result() -> ValidationResult {
    ValidationResult {
        results: vec![
            make_gate_result(Gate::Check, true, 1.0),
            make_gate_result(Gate::Test, false, 3.0),
            make_gate_result(Gate::Lint, false, 0.5),
        ],
    }
}

// ── Basic structure ────────────────────────────────────────

#[test]
fn pr_comment_has_header() {
    let md = generate_pr_comment(&all_pass_result(), None);
    assert!(md.contains("## magistr iteration summary"));
}

#[test]
fn pr_comment_has_gate_table() {
    let md = generate_pr_comment(&all_pass_result(), None);
    assert!(md.contains("| Gate | Status | Duration |"));
    assert!(md.contains("| check |"));
    assert!(md.contains("| test |"));
    assert!(md.contains("| lint |"));
}

#[test]
fn pr_comment_shows_pass_status() {
    let md = generate_pr_comment(&all_pass_result(), None);
    assert!(md.contains("✅ PASS"));
    assert!(md.contains("**All gates passed**"));
}

#[test]
fn pr_comment_shows_fail_status() {
    let md = generate_pr_comment(&mixed_result(), None);
    assert!(md.contains("❌ FAIL"));
    assert!(md.contains("**2 gate(s) failed**"));
}

#[test]
fn pr_comment_has_footer() {
    let md = generate_pr_comment(&all_pass_result(), None);
    assert!(md.contains("Generated by [magistr]"));
}

// ── Iteration context ──────────────────────────────────────

#[test]
fn pr_comment_with_iteration_shows_progress() {
    let ctx = IterationContext {
        iteration: 3,
        max_iterations: 10,
        spec_checked: 15,
        spec_total: 20,
        cost_usd: Some(1.50),
    };
    let md = generate_pr_comment(&all_pass_result(), Some(&ctx));
    assert!(md.contains("**Iteration** 3/10"));
    assert!(md.contains("15/20"));
    assert!(md.contains("75%"));
    assert!(md.contains("$1.50"));
}

#[test]
fn pr_comment_without_iteration_omits_progress() {
    let md = generate_pr_comment(&all_pass_result(), None);
    assert!(!md.contains("**Iteration**"));
    assert!(!md.contains("Spec progress"));
}

// ── Progress bar ───────────────────────────────────────────

#[test]
fn progress_bar_empty() {
    let bar = progress_bar(0, 10);
    assert_eq!(bar, "`[░░░░░░░░░░]`");
}

#[test]
fn progress_bar_full() {
    let bar = progress_bar(100, 10);
    assert_eq!(bar, "`[██████████]`");
}

#[test]
fn progress_bar_half() {
    let bar = progress_bar(50, 10);
    assert_eq!(bar, "`[█████░░░░░]`");
}
