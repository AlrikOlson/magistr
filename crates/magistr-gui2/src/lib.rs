//! The native GUI: the cockpit's own `Model`/`update`/`view`, laid out by its own taffy
//! tree, painted by a **second painter** ([`Painter`]) into a qs-gpu `DrawList`,
//! presented through wgpu in a winit window ([`Native`]; [`open`] is the fixture demo)
//! and rasterized on the CPU tier for goldens ([`Frame::still`]). Text is shaped by
//! qs-text over the same embedded faces the terminal stills draw with ([`fonts`]); the
//! pixel chrome is the terminal's own painters as textured quads ([`chrome`]); input is
//! winit's events as the cockpit's `Msg`, resolved through the terminal's hit registry
//! ([`input`]).
//!
//! Cells stay the layout unit ([`CellMetrics`]); `tests/paint_latency.rs` is the number
//! behind that.
//!
//! The framework is consumed by git rev; see the pin discipline in this crate's
//! `Cargo.toml`.

