#!/usr/bin/env python3
"""Ratchet imported Rust structure per file; no vendor-wide lint exemption.

Counts are a lexical guard, not a Rust parser or substitute for cargo/clippy.
Comments and strings are masked before brace counting. Imported inline tests
remain measured; new files and growth must satisfy the normal structure limits.
The checked-in baseline is reviewed source, never regenerated by this gate.
"""

import json
from pathlib import Path
import re
import sys


REVISION = "8c10c1fcfb479e90b33c59502eabd92586cf0761"
SUBSYSTEM = Path("subsystems/workflow")
CRATE = Path("crates/magistr-workflow")
BASELINE = SUBSYSTEM / "STRUCTURE_BASELINE.json"
LIMITS = {"public_items": 1, "inline_test_modules": 0, "long_functions": 0,
          "long_function_excess_lines": 0, "longest_function": 150}
RAW_STRING = re.compile(r'(?:br|cr|r)(#*)"')
CHARACTER = re.compile(r"'(?:\\(?:u\{[0-9a-fA-F_]+\}|x[0-9a-fA-F]{2}|.)|[^'\\\n])'")


def mask_literals(source):
    """Retain newlines/offsets while removing comments and Rust string/char text."""
    result = list(source)
    index = 0
    while index < len(source):
        start = index
        if source.startswith("//", index):
            newline = source.find("\n", index)
            index = len(source) if newline < 0 else newline
        elif source.startswith("/*", index):
            index += 2
            depth = 1
            while index < len(source) and depth:
                if source.startswith("/*", index):
                    depth += 1
                    index += 2
                elif source.startswith("*/", index):
                    depth -= 1
                    index += 2
                else:
                    index += 1
        else:
            raw = RAW_STRING.match(source, index)
            if raw:
                close = source.find('"' + raw[1], raw.end())
                index = len(source) if close < 0 else close + 1 + len(raw[1])
            elif source[index] == '"':
                index += 1
                while index < len(source):
                    if source[index] == "\\":
                        index += 2
                    elif source[index] == '"':
                        index += 1
                        break
                    else:
                        index += 1
            elif source[index] == "'":
                # Lifetime names have no trailing quote; character literals do.
                char = CHARACTER.match(source, index)
                if char:
                    index = char.end()
                else:
                    index += 1
                    continue
            else:
                index += 1
                continue
        for position in range(start, min(index, len(source))):
            if result[position] != "\n":
                result[position] = " "
    return "".join(result)


def measure(source):
    masked = mask_literals(source)
    public_items = len(re.findall(r"^pub (?:struct|enum|fn|trait|type|const|static|async fn)\b", masked, re.M))
    inline_tests = len(re.findall(r"\bmod\s+tests\s*\{", masked))
    functions = re.finditer(
        r"^[ \t]*(?:pub(?:\([^)]*\))?\s+)?(?:(?:async|const|unsafe|extern)\s+)*fn\s+[A-Za-z_]\w*",
        masked, re.M,
    )
    lengths = []
    for function in functions:
        opening = masked.find("{", function.end())
        terminator = masked.find(";", function.end())
        if opening < 0 or (terminator >= 0 and terminator < opening):
            continue
        depth = 1
        index = opening + 1
        while index < len(masked) and depth:
            if masked[index] == "{":
                depth += 1
            elif masked[index] == "}":
                depth -= 1
            index += 1
        if depth:
            raise ValueError("unbalanced function body; cargo must accept source before structure checks")
        lengths.append(masked[function.start():index].count("\n") + 1)
    return {"public_items": public_items, "inline_test_modules": inline_tests,
            "long_functions": sum(length > 150 for length in lengths),
            "long_function_excess_lines": sum(max(0, length - 150) for length in lengths),
            "longest_function": max(lengths, default=0)}


def measurements(root):
    crate = root / CRATE
    # Include every retained Cargo target, without scanning generated target/ files.
    files = list((crate / "src").rglob("*.rs"))
    files.extend((crate / "tests").rglob("*.rs"))
    return {str(path.relative_to(root)): measure(path.read_text()) for path in sorted(files)}


def check(root):
    baseline = json.loads((root / BASELINE).read_text())
    if baseline.get("version") != 1 or baseline.get("upstream_revision") != REVISION:
        return ["unknown baseline schema or upstream revision"]
    errors = []
    for file, current in measurements(root).items():
        previous = baseline["files"].get(file, {})
        for metric, value in current.items():
            limit = max(LIMITS[metric], previous.get(metric, 0))
            if value > limit:
                errors.append(f"{file}: {metric} grew to {value} (maximum {limit})")
    return errors


if __name__ == "__main__":
    try:
        failures = check(Path(sys.argv[1]).resolve())
    except (OSError, ValueError, KeyError) as error:
        failures = [str(error)]
    for failure in failures:
        print(f"ERROR: workflow-structure — {failure}", file=sys.stderr)
    if failures:
        sys.exit(1)
    print("OK: imported Rust structure stays within its per-file baseline; new violations are rejected")
