#!/usr/bin/env python3
"""Verify the owned reference bytes and native Cargo boundary, read-only.

UPSTREAM_MANIFEST inventories the entire audited Git tree, including exclusions.
LOCAL_CHANGES explicitly reviews deviations from included upstream bytes/modes.
Neither manifest nor the structure baseline is regenerated by this gate.
"""

import hashlib
import json
from pathlib import Path, PurePosixPath
import stat
import subprocess
import sys
import tomllib


REVISION = "2a2430bbcd5dcbed00920f92c6f3e6928f387d95"
TREE = "c264c99904d406721c2af2760cac2ceaec0aa4f9"
SUBSYSTEM = Path("subsystems/workspace")
REFERENCE = SUBSYSTEM / "reference"
NATIVE = Path("crates/magistr-workspace")
TOOLS = ("search", "map", "read", "edit", "files", "run", "script", "undo")


def safe_relative(path):
    parsed = PurePosixPath(path)
    return bool(parsed.parts) and str(parsed) == path and not parsed.is_absolute() and ".." not in parsed.parts


def git_object(kind, data):
    return hashlib.sha1(f"{kind} {len(data)}\0".encode() + data).hexdigest()


def tree_digest(entries):
    """Reconstruct the pinned Git tree, so excluded records cannot disappear."""
    tree = {}
    for entry in entries:
        cursor = tree
        parts = PurePosixPath(entry["path"]).parts
        if not safe_relative(entry["path"]):
            raise ValueError(f"invalid manifest path: {entry['path']}")
        for part in parts[:-1]:
            cursor = cursor.setdefault(part, {})
        if parts[-1] in cursor:
            raise ValueError(f"duplicate manifest path: {entry['path']}")
        cursor[parts[-1]] = (entry["mode"], entry["git_blob"])

    def digest(directory):
        rows = []
        for name, item in directory.items():
            mode, oid = ("40000", digest(item)) if isinstance(item, dict) else item
            sort_name = name + ("/" if mode == "40000" else "")
            rows.append((sort_name.encode(), f"{mode} {name}\0".encode() + bytes.fromhex(oid)))
        return git_object("tree", b"".join(row for _, row in sorted(rows)))

    return digest(tree)


def reference_errors(root):
    errors = []
    manifest = json.loads((root / SUBSYSTEM / "UPSTREAM_MANIFEST.json").read_text())
    changes = json.loads((root / SUBSYSTEM / "LOCAL_CHANGES.json").read_text())
    if manifest.get("version") != 1 or manifest.get("upstream_revision") != REVISION:
        return ["unknown upstream manifest schema or revision"]
    if changes.get("version") != 1:
        return ["unknown local change manifest schema"]
    entries = manifest["files"]
    if manifest.get("upstream_tree") != TREE or tree_digest(entries) != TREE:
        errors.append("upstream manifest does not reconstruct the audited Git tree")
    included = {entry["path"]: entry for entry in entries if entry["included"]}
    if len(entries) != 525 or len(included) != 428:
        errors.append("expected 525 audited entries: 428 included and 97 explicitly excluded")
    deltas = {}
    original_paths = {entry["path"] for entry in entries}
    for delta in changes["files"]:
        path = delta["path"]
        added = delta.get("added", False)
        valid_origin = path not in original_paths if added else path in included
        if (path in deltas or not safe_relative(path) or not valid_origin
                or delta.get("mode") not in ("100644", "100755") or not delta.get("reason", "").strip()):
            errors.append(f"invalid, duplicate, or unexplained local delta: {path}")
            continue
        deltas[path] = delta
    for entry in entries:
        relative = entry["path"]
        if not entry.get("reason", "").strip():
            errors.append(f"missing inclusion/exclusion rationale: {relative}")
        path = root / REFERENCE / relative
        if not entry["included"]:
            if path.exists() or path.is_symlink():
                errors.append(f"excluded upstream path was materialized: {relative}")
            continue
        if not path.is_file() or path.is_symlink() or not path.resolve().is_relative_to(root / REFERENCE):
            errors.append(f"missing, non-regular, or escaping reference input: {relative}")
            continue
        data = path.read_bytes()
        expected = deltas.get(relative, entry)
        mode = "100755" if path.stat().st_mode & stat.S_IXUSR else "100644"
        if hashlib.sha256(data).hexdigest() != expected["sha256"] or mode != expected["mode"]:
            errors.append(f"reference bytes/mode differ without a matching reviewed delta: {relative}")
        if relative not in deltas:
            if len(data) != entry["bytes"] or git_object("blob", data) != entry["git_blob"]:
                errors.append(f"reference blob differs from audited source: {relative}")
        elif expected["sha256"] == entry["sha256"] and expected["mode"] == entry["mode"]:
            errors.append(f"local delta is stale; file matches upstream: {relative}")
    for relative, delta in deltas.items():
        if not delta.get("added", False):
            continue
        path = root / REFERENCE / relative
        if not path.is_file() or path.is_symlink() or not path.resolve().is_relative_to(root / REFERENCE):
            errors.append(f"missing, non-regular, or escaping local addition: {relative}")
            continue
        mode = "100755" if path.stat().st_mode & stat.S_IXUSR else "100644"
        if hashlib.sha256(path.read_bytes()).hexdigest() != delta["sha256"] or mode != delta["mode"]:
            errors.append(f"local addition bytes/mode differ from reviewed delta: {relative}")
    return errors


def cargo_errors(root):
    errors = []

    def require(condition, message):
        if not condition:
            errors.append(message)

    native = tomllib.loads((root / NATIVE / "Cargo.toml").read_text())
    require("no-bindings" not in native.get("features", {}),
            "native library must not depend on the reference no-bindings test feature")
    require(not (root / NATIVE / "build.rs").exists(), "native library must not carry the NAPI build script")
    result = subprocess.run(["cargo", "metadata", "--locked", "--format-version", "1"],
                            cwd=root, capture_output=True, text=True, check=False)
    if result.returncode:
        return errors + [f"locked Cargo metadata failed: {result.stderr.strip()}"]
    metadata = json.loads(result.stdout)
    require(Path(metadata["workspace_root"]).resolve() == root, "Cargo metadata describes another workspace")
    packages = {package["id"]: package for package in metadata["packages"]}
    candidates = [package for package in packages.values() if package["name"] == "magistr-workspace"]
    require(len(candidates) == 1, "expected exactly one magistr-workspace package")
    if len(candidates) != 1:
        return errors
    workspace = candidates[0]
    require(workspace["source"] is None and Path(workspace["manifest_path"]).resolve() == root / NATIVE / "Cargo.toml",
            "magistr-workspace must resolve from its repository-local manifest")
    require(workspace["id"] in metadata["workspace_members"], "native workspace library must participate in root workspace checks")
    require(workspace["license"] == "Apache-2.0", "native library must retain its Apache-2.0 license")
    library = [target for target in workspace["targets"] if "lib" in target["kind"] or "rlib" in target["kind"]]
    require(len(library) == 1 and set(library[0]["crate_types"]) <= {"lib", "rlib"},
            "native workspace target must be an ordinary Rust library")
    require(not any("custom-build" in target["kind"] for target in workspace["targets"]),
            "native workspace must not have a build-script target")
    nodes = {node["id"]: node for node in metadata["resolve"]["nodes"]}

    def runtime_graph(seeds):
        reached = set()
        pending = list(seeds)
        while pending:
            current = pending.pop()
            if current in reached:
                continue
            reached.add(current)
            pending.extend(dependency["pkg"] for dependency in nodes[current]["deps"]
                           if any(kind["kind"] != "dev" for kind in dependency["dep_kinds"]))
        return reached

    native_graph = runtime_graph([workspace["id"]])
    product_graph = runtime_graph([workspace["id"]] + [package["id"] for package in packages.values()
                                                       if package["name"] == "magistr-cli"])
    for package_id in product_graph:
        package = packages[package_id]
        require(not package["name"].startswith("napi") and package["name"] != "workbench-core",
                f"production Rust graph includes reference binding package {package['name']}")
        if package["source"] is None:
            require(Path(package["manifest_path"]).resolve().is_relative_to(root),
                    f"production package resolves outside the repository: {package['name']}")
    majors = {int(packages[package_id]["version"].split(".")[0]) for package_id in native_graph
              if packages[package_id]["name"] == "wasmtime"}
    # tree-sitter 0.27 moved the parser lane onto the extension host's Wasmtime,
    # so both lanes compile one major; a split would reintroduce the double
    # compile and the Mach-port trap hazard the sandbox comments describe.
    require(majors == {48}, "native default features must run the parser and extension lanes on one Wasmtime major (48)")
    return errors


def check(root):
    errors = reference_errors(root)
    required = [SUBSYSTEM / path for path in ("THIRD_PARTY_NOTICES.md", "PROVENANCE.md", "FEATURE_INVENTORY.md", "NATIVE_IMPORTS.json",
                "LICENSES/quickjs-ng-0.16.2-MIT.txt", "LICENSES/tree-sitter-gleam-1.0.0-Apache-2.0.txt")]
    required += [REFERENCE / path for path in ("Cargo.lock", "bun.lock", "rust-toolchain.toml",
                 "src/protocol/server.ts", "src/protocol/workspace.ts", "src/tools/write-engine.ts",
                 "schemas/envelope.schema.json", "schemas/error-taxonomy.json", "wit/baseline.json")]
    required += [REFERENCE / "schemas/tools" / f"{tool}.input.schema.json" for tool in TOOLS]
    required += [NATIVE / "src" / f"{module}.rs" for module in ("lib", "engine", "indexer", "langs", "lang_registry", "sandbox")]
    for relative in required:
        path = root / relative
        if not path.is_file() or path.stat().st_size == 0:
            errors.append(f"missing or empty adoption input: {relative}")
    package = json.loads((root / REFERENCE / "package.json").read_text())
    wasm = package.get("scripts", {}).get("build:core:wasm", "")
    if "--no-default-features" not in wasm.split() or "wasm32-wasip1-threads" not in wasm:
        errors.append("reference WASM fallback must disable native-only default features")
    errors.extend(cargo_errors(root))
    return errors


if __name__ == "__main__":
    try:
        failures = check(Path(sys.argv[1]).resolve())
    except (OSError, ValueError, KeyError, TypeError) as error:
        failures = [str(error)]
    for failure in failures:
        print(f"ERROR: workspace-source — {failure}", file=sys.stderr)
    if failures:
        sys.exit(1)
    print("OK: audited reference inputs retained; magistr-workspace is a local native library without NAPI")
