/**
 * Emit `src/generated/schemas.ts` from `schemas/` — the single source of truth
 * for every MCP `inputSchema` / `outputSchema` (Constitution V, SDD §4.2).
 *
 *   bun run codegen         rewrite the generated module
 *   bun run codegen:check   fail (exit 1) if the generated module is stale
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaDir = join(repoRoot, "schemas");
const toolDir = join(schemaDir, "tools");
const outFile = join(repoRoot, "src", "generated", "schemas.ts");

const TOOL_SUFFIX = ".input.schema.json";

type JsonObject = Record<string, unknown>;

async function readJson(path: string): Promise<JsonObject> {
  const raw = await readFile(path, "utf8");
  const parsed: unknown = JSON.parse(raw);
  if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) {
    throw new Error(`${path}: expected a JSON Schema object`);
  }
  return parsed as JsonObject;
}

/** Tool names come from the directory listing, sorted, so output is deterministic. */
async function toolNames(): Promise<string[]> {
  const entries = await readdir(toolDir);
  return entries
    .filter((name) => name.endsWith(TOOL_SUFFIX))
    .map((name) => name.slice(0, -TOOL_SUFFIX.length))
    .sort();
}

function literal(value: JsonObject, indent: number): string {
  return JSON.stringify(value, null, 2)
    .split("\n")
    .join(`\n${" ".repeat(indent)}`);
}

async function render(): Promise<string> {
  const envelope = await readJson(join(schemaDir, "envelope.schema.json"));
  const taxonomy = await readJson(join(schemaDir, "error-taxonomy.json"));
  const names = await toolNames();
  if (names.length === 0) {
    throw new Error(`no ${TOOL_SUFFIX} files found in ${toolDir}`);
  }

  const entries: string[] = [];
  for (const name of names) {
    const input = await readJson(join(toolDir, `${name}${TOOL_SUFFIX}`));
    entries.push(
      [
        `  ${JSON.stringify(name)}: {`,
        `    inputSchema: ${literal(input, 4)},`,
        "    outputSchema: envelopeSchema,",
        "  },",
      ].join("\n"),
    );
  }

  return [
    "// Code generated by scripts/generate-schemas.ts. DO NOT EDIT.",
    "// Source of truth: schemas/ (Constitution V, SDD §4.2).",
    "// Regenerate with `bun run codegen`; CI enforces `bun run codegen:check`.",
    "",
    `export const envelopeSchema = ${literal(envelope, 0)} as const;`,
    "",
    `export const errorTaxonomy = ${literal(taxonomy, 0)} as const;`,
    "",
    "export const toolSchemas = {",
    ...entries,
    "} as const;",
    "",
    "export type ToolName = keyof typeof toolSchemas;",
    "",
  ].join("\n");
}

const check = process.argv.includes("--check");
const generated = await render();

if (check) {
  const current = await readFile(outFile, "utf8").catch(() => null);
  if (current !== generated) {
    console.error(
      current === null
        ? `codegen drift: ${outFile} is missing. Run \`bun run codegen\`.`
        : `codegen drift: ${outFile} does not match schemas/. Run \`bun run codegen\`.`,
    );
    process.exit(1);
  }
  console.log("codegen: generated schemas match schemas/");
} else {
  await writeFile(outFile, generated, "utf8");
  console.log(`codegen: wrote ${outFile}`);
}
